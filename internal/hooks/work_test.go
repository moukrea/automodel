const workGoal = "Find why checkouts hand the same connection to two workers under load, and fix it"

// workSession sets up a warm session whose decision in force is tier and
// mode, and whose work in progress is work (at mode).
func workSession(t *testing.T, env *router.Env, sid, tier, mode, work string) {
	t.Helper()
	warmSession(t, env, sid, tier, 300_000)
	c := env.Catalog
	_, effort, wf := c.Resolve(c.Tier(catalog.ScopeMain, tier), mode)
	env.State.Update(sid, func(s *state.Session) bool {
		s.Main.Effort, s.Main.Mode, s.Main.Workflows = effort, mode, wf
		s.UltracodeOn, s.UltracodeEpoch = wf, s.Main.Epoch
		s.Work = &state.Work{Tier: work, Mode: mode, Goal: workGoal, Since: time.Now().Add(-time.Hour)}
		return true
	})
}

// busyTranscript is a turn still running: the last message called a tool
// and no turn end followed.
func busyTranscript(t *testing.T) string {
	p := filepath.Join(t.TempDir(), "busy.jsonl")
	os.WriteFile(p, []byte(strings.Join([]string{
		`{"type":"user","message":{"role":"user","content":"Add the price column to the CSV export"}}`,
		`{"type":"assistant","message":{"role":"assistant","stop_reason":"tool_use","content":[{"type":"tool_use","id":"t1","name":"Edit","input":{}}]}}`,
		`{"type":"user","message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t1","content":"ok"}]}}`,
	}, "\n")+"\n"), 0o600)
	return p
}

// startedTranscript is a turn that just started: its prompt is written,
// none of the turn's own entries yet (Claude Code writes them in batches).
func startedTranscript(t *testing.T) string {
	p := filepath.Join(t.TempDir(), "started.jsonl")
	os.WriteFile(p, []byte(strings.Join([]string{
		`{"type":"assistant","message":{"role":"assistant","stop_reason":"end_turn","content":[{"type":"text","text":"The race is in the pool's checkout path."}]}}`,
		`{"type":"system","subtype":"turn_duration"}`,
		`{"type":"user","message":{"role":"user","content":"Add the price column to the CSV export"}}`,
	}, "\n")+"\n"), 0o600)
	return p
}

// shellTranscript is a turn that ended, then a shell command run with "!"
// (Claude Code's bash mode: a caveat, its input, its output), and no
// assistant entry after it.
func shellTranscript(t *testing.T) string {
	p := filepath.Join(t.TempDir(), "shell.jsonl")
	os.WriteFile(p, []byte(strings.Join([]string{
		`{"type":"user","message":{"role":"user","content":"Find why checkouts hand the same connection to two workers under load, and fix it"}}`,
		`{"type":"assistant","message":{"role":"assistant","stop_reason":"end_turn","content":[{"type":"text","text":"Fixed: the pool now leases under the lock. Tests pass."}]}}`,
		`{"type":"system","subtype":"stop_hook_summary"}`,
		`{"type":"user","isMeta":true,"message":{"role":"user","content":"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"}}`,
		`{"type":"user","message":{"role":"user","content":"<bash-input>git status</bash-input>"}}`,
		`{"type":"user","message":{"role":"user","content":"<bash-stdout>On branch main\nnothing to commit</bash-stdout><bash-stderr></bash-stderr>"}}`,
	}, "\n")+"\n"), 0o600)
	return p
}

