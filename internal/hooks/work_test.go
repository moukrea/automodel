// A go-ahead carries the work in progress on: after a side question
// lowered the tier, "vas-y" brings the work's tier and mode back without
// asking Jev; after a wrap-up it is routed (Jev's relation says whether it
// reopens the work); a go-ahead to a proposal is routed, not below the
// work.
func TestGoAheadRestoresWork(t *testing.T) {
	fj := &fakeJev{}
	env := setup(t, fj)
	cwd := t.TempDir()
	decide := func(sid, p, tp string) {
		run(t, env, "decide", map[string]any{"session_id": sid, "prompt": p, "cwd": cwd, "transcript_path": tp})
	}
	// A side question answered at low (an older session, or one Jev read as
	// separate); the work in progress is still xhigh.
	workSession(t, env, "g1", "low", "", "xhigh")
	n := fj.calls()
	decide("g1", "Oui, vas-y !", "")
	s, _ := env.State.Load("g1")
	if fj.calls() != n || s.Main.Tier != "xhigh" || s.Main.Effort != "xhigh" || s.PendingEffort == nil || s.PendingEffort.Effort != "xhigh" {
		t.Fatalf("go-ahead after a side question: %d calls, %+v, pending %+v", fj.calls()-n, s.Main, s.PendingEffort)
	}
	all, _ := ledger.Decisions(env.Cfg.Ledger)
	if d := all[len(all)-1]; d.Hold != "go-ahead: back to the work in progress" || d.From != "low" || d.Chosen != "xhigh" || d.Kept {
		t.Errorf("ledger = %+v", d)
	}
	// The same flow, live: a side question in an ultracode session runs
	// without the mode, the go-ahead restores it.
	workSession(t, env, "g2", "xhigh", "ultracode", "xhigh")
	fj.answers = []fa{{tier: "low", conf: 0.95, ultra: 0.9, rel: "side_question"}}
	decide("g2", "how many handlers are left?", "")
	if s, _ = env.State.Load("g2"); s.Main.Tier != "xhigh" || s.Main.Mode != "" || s.UltracodeOn || s.Work.Mode != "ultracode" {
		t.Fatalf("side question: %+v, work %+v", s.Main, s.Work)
	}
	n = fj.calls()
	decide("g2", "ok, go", "")
	if s, _ = env.State.Load("g2"); fj.calls() != n || s.Main.Tier != "xhigh" || s.Main.Mode != "ultracode" || !s.UltracodeOn {
		t.Fatalf("go-ahead after a side question: %+v", s.Main)
	}
	// Unchanged: only logged as kept.
	decide("g2", "continue", "")
	if s, _ = env.State.Load("g2"); fj.calls() != n || s.Main.Tier != "xhigh" {
		t.Fatalf("plain go-ahead: %+v", s.Main)
	}
	// A side question answered above the work (ultrathink) raised that
	// answer only: the go-ahead goes back to the work's level.
	workSession(t, env, "g5", "low", "", "low")
	fj.answers = []fa{{tier: "low", conf: 0.9, rel: "side_question"}}
	decide("g5", "ultrathink: is the rename safe for the plugin API?", "")
	if s, _ = env.State.Load("g5"); s.Main.Tier != "xhigh" || s.Work.Tier != "low" {
		t.Fatalf("ultrathink side question: %+v, work %+v", s.Main, s.Work)
	}
	n = fj.calls()
	decide("g5", "ok, continue", "")
	if s, _ = env.State.Load("g5"); fj.calls() != n || s.Main.Tier != "low" {
		t.Errorf("go-ahead after an ultrathink side question: %+v", s.Main)
	}
	// After a wrap-up, a go-ahead or an acknowledgement is routed: "looks
	// good." on a done xhigh fix (held-out run 1 carried it at xhigh) gets
	// its own level; "vas-y" Jev reads as more work reopens it.
	warmSession(t, env, "g4", "xhigh", 300_000)
	fj.answers = []fa{{tier: "low", conf: 0.95, rel: "wrap_up"}}
	decide("g4", "résume ce que tu as fait", "")
	n = fj.calls()
	fj.answers = []fa{{tier: "low", conf: 0.95, rel: "aside", relP: 0.9}}
	decide("g4", "looks good.", "")
	if s, _ = env.State.Load("g4"); fj.calls() != n+1 || fj.last().Questions[jev.QRelation].Type != "choice" || s.Main.Tier != "low" || s.Work == nil || !s.Work.Done || s.Work.Tier != "xhigh" {
		t.Fatalf("acknowledgement of a done work (%d calls): %+v, work %+v", fj.calls()-n, s.Main, s.Work)
	}
	fj.answers = []fa{{tier: "low", conf: 0.95, rel: "continue"}}
	decide("g4", "vas-y", "")
	if s, _ = env.State.Load("g4"); s.Main.Tier != "xhigh" || s.Work.Done || s.Work.Tier != "xhigh" {
		t.Fatalf("go-ahead reopening a done work: %+v, work %+v", s.Main, s.Work)
	}
	n = fj.calls()
	// A go-ahead to a proposal is routed, without the relation question,
	// and not below the work in progress.
	tp := filepath.Join(cwd, "t.jsonl")
	os.WriteFile(tp, []byte(`{"type":"assistant","message":{"role":"assistant","stop_reason":"end_turn","content":[{"type":"text","text":"Both call sites read the lease without the lock. Want me to fix the second one too?"}]}}`+"\n"), 0o600)
	workSession(t, env, "g3", "xhigh", "", "xhigh")
	fj.answers = []fa{{tier: "low", conf: 0.9}}
	decide("g3", "yes", tp)
	if s, _ = env.State.Load("g3"); fj.calls() != n+1 || s.Main.Tier != "xhigh" || fj.last().Questions[jev.QRelation].Type != "" {
		t.Fatalf("go-ahead to a proposal: %+v, questions %v", s.Main, fj.last().Questions)
	}
	for _, p := range []string{"oui, vas-y", "ok, go", "yes, do it", "Parfait, fonce !", "let's go", "go for it", "ship it", "on y va", "c'est parti", "oui continue", "continue then"} {
		if !router.GoAhead(p) {
			t.Errorf("GoAhead(%q) = false", p)
		}
	}
	for _, p := range []string{"continue?", "go, and also add rate limiting", "oui mais garde l'ancienne API", "continue the refactor of the payment module"} {
		if router.GoAhead(p) {
			t.Errorf("GoAhead(%q) = true", p)
		}
	}
}

